  getLMS(metric, sex, ageMonths) {
    const table = this[metric];
    if (!table) return null;
    const genderKey = sex === 'girl' ? 'girl' : 'boy';
    const pts = table[genderKey];
    const keys = Object.keys(pts).map(Number).sort((a, b) => a - b);
    const m = Math.max(0, Math.min(12, ageMonths));
    for (let i = 0; i < keys.length - 1; i++) {
      const m0 = keys[i], m1 = keys[i + 1];
      if (m >= m0 && m <= m1) {
        const t = (m - m0) / (m1 - m0);
        const [L0, M0, S0] = pts[m0];
        const [L1, M1, S1] = pts[m1];
        return [L0 + (L1 - L0) * t, M0 + (M1 - M0) * t, S0 + (S1 - S0) * t];
      }
    }
    return pts[keys[keys.length - 1]];
  },

  valueFromZ(L, M, S, Z) {
    if (Math.abs(L) < 1e-5) return M * Math.exp(S * Z);
    return M * Math.pow(1 + L * S * Z, 1 / L);
  },

  zScore(metric, sex, ageMonths, value) {
    const lms = this.getLMS(metric, sex, ageMonths);
    if (!lms || value <= 0) return null;
    const [L, M, S] = lms;
    if (Math.abs(L) < 1e-5) return Math.log(value / M) / S;
    return (Math.pow(value / M, L) - 1) / (L * S);
  },

  normalCDF(z) {
    // Abramowitz & Stegun approximation
    const t = 1 / (1 + 0.2316419 * Math.abs(z));
    const d = 0.3989423 * Math.exp(-z * z / 2);
    const p = d * t * (0.3193815 + t * (-0.3565638 + t * (1.781478 + t * (-1.821256 + t * 1.330274))));
    return z > 0 ? 1 - p : p;
  },

  evaluate(metric, sex, ageMonths, value) {
    const z = this.zScore(metric, sex, ageMonths, value);
    if (z === null || isNaN(z)) return null;
    const pct = Math.max(1, Math.min(99, Math.round(this.normalCDF(z) * 100)));
    return { z, pct };
  }
